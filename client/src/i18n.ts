export const EN_STRINGS: Readonly<Record<StringKey, string>> = en;
const LOCALES: Record<string, Partial<Record<string, string>>> = { bn, gu, kn, ml, mr, ta, te };

/** A string in the chosen language, falling back to English when a translation is missing. */
export function lookupString(lang: Lang, key: string): string | undefined {
  if (lang === "hi") return (hi as Record<string, string>)[key];
  if (lang === "en") return (en as Record<string, string>)[key];
  return LOCALES[lang]?.[key] ?? (en as Record<string, string>)[key];
}

export function translate(lang: Lang, key: StringKey, vars: Record<string, string | number> = {}): string {
  let s = lookupString(lang, key) ?? en[key] ?? key;
  for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}
